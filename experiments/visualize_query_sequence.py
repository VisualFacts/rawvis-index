"""
Visualize a query sequence on an interactive Leaflet map with animation.

Reads the query file generated by the Java Experiments class
(command: generateAndSaveQuerySequence) and produces an HTML file with
playback controls, phase coloring, and a trail of previous viewports.

Usage:
    # 1. Generate queries from the scenario:
    java -jar target/experiments.jar \\
        -c generateAndSaveQuerySequence \\
        -scenario taxi_zoom \\
        -configFile src/main/resources/experiments/experiment_scenarios.yaml \\
        -out experiments/taxi_zoom_queries.txt

    # 2. Visualize:
    python3 visualize_query_sequence.py taxi_zoom_queries.txt

    # Or specify a scenario name to generate + visualize in one step:
    python3 visualize_query_sequence.py --scenario taxi_zoom
"""

import json
import os
import re
import subprocess
import webbrowser

# Phase colors for visualization
PHASE_COLORS = ["blue", "red", "green", "orange", "purple", "cyan", "magenta", "brown"]

# Project root (relative to this script in experiments/)
PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CONFIG_FILE = os.path.join(PROJECT_ROOT, "src/main/resources/experiments/experiment_scenarios.yaml")
JAR_FILE = os.path.join(PROJECT_ROOT, "target/experiments.jar")
NATIVE_LIB = os.path.join(PROJECT_ROOT, "native/build")


# --- Parse query file ---

def parse_query_line(line):
    """Parse a serialized query line: (xMin..xMax),(yMin..yMax)|filters|groupBy|measures|opType"""
    parts = line.strip().split("|")
    if len(parts) != 5:
        return None

    rect_str = parts[0]
    op_type = parts[4] if parts[4] != "null" else "Q0"

    # Parse "(xMin..xMax),(yMin..yMax)"
    match = re.match(r"\(([^)]+)\),\(([^)]+)\)", rect_str)
    if not match:
        return None

    x_parts = match.group(1).split("..")
    y_parts = match.group(2).split("..")

    return {
        "xLow": float(x_parts[0]),
        "xHigh": float(x_parts[1]),
        "yLow": float(y_parts[0]),
        "yHigh": float(y_parts[1]),
        "opType": op_type,
    }


def detect_phases(queries):
    """Detect phase boundaries from operation type transitions."""
    if not queries:
        return []
    phases = []
    current_op = queries[0]["opType"]
    phase_start = 0
    phase_idx = 0

    for i in range(1, len(queries)):
        if queries[i]["opType"] != current_op:
            phases.append({"name": f"phase_{phase_idx}_{current_op}", "start": phase_start, "end": i - 1, "op": current_op})
            current_op = queries[i]["opType"]
            phase_start = i
            phase_idx += 1

    phases.append({"name": f"phase_{phase_idx}_{current_op}", "start": phase_start, "end": len(queries) - 1, "op": current_op})
    return phases


def load_queries(filepath):
    """Load and parse queries from a file generated by generateAndSaveQuerySequence."""
    queries = []
    with open(filepath) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            q = parse_query_line(line)
            if q:
                queries.append(q)
    return queries


def generate_query_file(scenario, out_file):
    """Run the Java generateAndSaveQuerySequence command."""
    if not os.path.exists(JAR_FILE):
        print(f"Jar not found at {JAR_FILE}. Building...")
        subprocess.check_call(["mvn", "package", "-q", "-DskipTests"], cwd=PROJECT_ROOT)

    cmd = [
        "java", f"-Djava.library.path={NATIVE_LIB}",
        "-jar", JAR_FILE,
        "-c", "generateAndSaveQuerySequence",
        "-scenario", scenario,
        "-configFile", CONFIG_FILE,
        "-out", out_file,
    ]
    print(f"Generating queries: {' '.join(cmd)}")
    subprocess.check_call(cmd, cwd=PROJECT_ROOT)
    return out_file


